//! THE PARITY GATES (claricle/emf#90): for the corpus,
//! * the round trip — EMF → VIM → SVG → VIM → EMF — must equal the Ruby
//!   pipeline's EMF bytes file-by-file, and
//! * the direct SVG → EMF translation must equal the Ruby translation's
//!   bytes on the same fixtures.
//!
//! Environment:
//! * `EMF_FIXTURE_ROOT` — the pinned external emf checkout (the corpus
//!   EMF sources live under spec/fixtures/{emf,emf-ea,simple});
//! * `EMF_GOLDEN_ROOT` — the emfsvg checkout's spec/fixtures/golden
//!   directory (the Ruby forward renderer's reference SVG bytes);
//! * `EMF_REVERSE_GOLDEN_ROOT` — the Ruby SVG → EMF translation's bytes
//!   (generated by vectory-rs/scripts/gen_reverse_golden.rb).
//!
//! When any variable is unset the gate skips (CI without the pinned
//! corpus is not a failure); a local run reports the counts.

use std::collections::BTreeMap;
use std::path::PathBuf;

use eikogram_to_emf::drawing_to_emf;
use eikogram_to_svg::drawing_to_svg;
use emf_to_eikogram::{render, RenderOptions};
use svg_to_eikogram::svg_to_eikogram;

/// The SVG model's documented non-representable quirk normalization: the
/// reference renderer emits whitespace inside the tag grammar that XML
/// parsing discards (extra spaces between attributes, `style ="..."`,
/// space before `/>`). Byte comparison applies the same normalization to
/// both sides, exactly as the vectory crate's emfsvg fidelity contract
/// defines it. Attribute values are never touched (quoted regions are
/// verbatim), so quirks inside values — `translate(0.0000, 0.00 00)`, path
/// `d` spacing — compare byte-for-byte.
fn normalize_quirks(input: &str) -> String {
    let bytes = input;
    let mut out = String::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        let rest = &bytes[i..];
        if rest.starts_with("<![CDATA[") {
            let Some(end) = rest.find("]]>") else {
                out.push_str(rest);
                break;
            };
            let end = end + "]]>".len();
            out.push_str(&rest[..end]);
            i += end;
            continue;
        }
        if rest.starts_with("<!--") {
            let Some(end) = rest.find("-->") else {
                out.push_str(rest);
                break;
            };
            let end = end + "-->".len();
            out.push_str(&rest[..end]);
            i += end;
            continue;
        }
        let ch = rest.chars().next().expect("non-empty rest");
        if ch == '<' {
            let (consumed, normalized) = normalize_header(rest);
            out.push_str(&normalized);
            i += consumed;
            continue;
        }
        out.push(ch);
        i += ch.len_utf8();
    }
    out
}

/// Normalizes one markup header: whitespace outside quoted attribute values
/// collapses to a single space, disappears before `=`, `/>`, and `>`.
fn normalize_header(header: &str) -> (usize, String) {
    let mut out = String::new();
    let mut chars = header.char_indices();
    let mut in_quotes = false;
    while let Some((idx, ch)) = chars.next() {
        match ch {
            '"' if in_quotes => {
                in_quotes = false;
                out.push(ch);
            }
            '"' => {
                in_quotes = true;
                out.push(ch);
            }
            '>' if !in_quotes => {
                out.push('>');
                return (idx + 1, out);
            }
            c if c.is_whitespace() && !in_quotes => {
                let after = &header[idx + c.len_utf8()..];
                let trimmed = after.trim_start();
                let skipped = after.len() - trimmed.len();
                for _ in 0..skipped {
                    chars.next();
                }
                let next = trimmed.chars().next();
                match next {
                    Some('=') | Some('>') => {}
                    Some('/') if trimmed.starts_with("/>") => {}
                    Some(_) => out.push(' '),
                    None => {
                        out.push(' ');
                        return (header.len(), out);
                    }
                }
            }
            c => out.push(c),
        }
    }
    (header.len(), out)
}

struct Corpus {
    /// name → EMF source bytes
    sources: BTreeMap<String, Vec<u8>>,
    /// name → golden SVG bytes (the forward renderer's reference)
    goldens: BTreeMap<String, String>,
    /// name → the Ruby SVG → EMF translation's bytes
    reverse_goldens: BTreeMap<String, Vec<u8>>,
}

fn load_corpus() -> Option<Corpus> {
    let fixture_root = std::env::var("EMF_FIXTURE_ROOT").ok()?;
    let golden_root = std::env::var("EMF_GOLDEN_ROOT").ok()?;
    let reverse_root = std::env::var("EMF_REVERSE_GOLDEN_ROOT").ok()?;
    let fixture_root = PathBuf::from(fixture_root);
    let golden_root = PathBuf::from(golden_root);
    let reverse_root = PathBuf::from(reverse_root);

    let mut sources = BTreeMap::new();
    for dir in [
        "spec/fixtures/emf",
        "spec/fixtures/emf-ea",
        "spec/fixtures/simple",
    ] {
        let Ok(entries) = std::fs::read_dir(fixture_root.join(dir)) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().is_some_and(|e| e == "emf") {
                let name = path
                    .file_name()?
                    .to_string_lossy()
                    .trim_end_matches(".emf")
                    .to_string();
                let bytes = std::fs::read(&path).ok()?;
                sources.insert(name, bytes);
            }
        }
    }

    let mut goldens = BTreeMap::new();
    for entry in std::fs::read_dir(&golden_root).ok()?.flatten() {
        let path = entry.path();
        if path.extension().is_some_and(|e| e == "svg") {
            let name = path
                .file_name()?
                .to_string_lossy()
                .trim_end_matches(".svg")
                .to_string();
            let content = std::fs::read_to_string(&path).ok()?;
            goldens.insert(name, content);
        }
    }

    let mut reverse_goldens = BTreeMap::new();
    for entry in std::fs::read_dir(&reverse_root).ok()?.flatten() {
        let path = entry.path();
        if path.extension().is_some_and(|e| e == "emf") {
            let name = path
                .file_name()?
                .to_string_lossy()
                .trim_end_matches(".emf")
                .to_string();
            let bytes = std::fs::read(&path).ok()?;
            reverse_goldens.insert(name, bytes);
        }
    }
    Some(Corpus {
        sources,
        goldens,
        reverse_goldens,
    })
}

/// The full round trip: EMF bytes → VIM → SVG → VIM → EMF bytes.
fn round_trip(emf_bytes: &[u8]) -> Result<(String, Vec<u8>), String> {
    let document = emf_core::parse(emf_bytes, &emf_core::ParseLimits::default())
        .map_err(|e| format!("parse: {e}"))?;
    let drawing =
        render(&document, &RenderOptions::default()).map_err(|e| format!("render: {e}"))?;
    let svg = drawing_to_svg(&drawing);
    let reverse = svg_to_eikogram(&svg).map_err(|e| format!("ingest: {e}"))?;
    let bytes = drawing_to_emf(&reverse).map_err(|e| format!("lower: {e}"))?;
    Ok((svg, bytes))
}

/// The direct translation: golden SVG bytes → VIM → EMF bytes.
fn direct(svg: &str) -> Result<Vec<u8>, String> {
    let reverse = svg_to_eikogram(svg).map_err(|e| format!("ingest: {e}"))?;
    drawing_to_emf(&reverse).map_err(|e| format!("lower: {e}"))
}

/// First-difference report for a mismatch (the gates' diagnostics).
fn first_diff(expected: &[u8], actual: &[u8]) -> String {
    let common = expected
        .iter()
        .zip(actual.iter())
        .take_while(|(a, b)| a == b)
        .count();
    let context = |bytes: &[u8]| -> String {
        let start = common.saturating_sub(80);
        let end = (common + 80).min(bytes.len());
        let slice = &bytes[start.min(end)..end];
        slice
            .iter()
            .map(|b| {
                if b.is_ascii_graphic() || *b == b' ' {
                    *b as char
                } else {
                    '.'
                }
            })
            .collect()
    };
    format!(
        "first difference at byte {common} (golden {} bytes, rust {} bytes):\n  golden: …{}…\n  rust:   …{}…",
        expected.len(),
        actual.len(),
        context(expected),
        context(actual)
    )
}

#[test]
fn reverse_round_trip_gate() {
    let Some(corpus) = load_corpus() else {
        eprintln!(
            "parity corpus not configured (EMF_FIXTURE_ROOT / EMF_GOLDEN_ROOT / \
             EMF_REVERSE_GOLDEN_ROOT unset); skipping"
        );
        return;
    };

    let mut matched: Vec<String> = Vec::new();
    let mut mismatches: Vec<(String, String)> = Vec::new();
    let mut errors: Vec<(String, String)> = Vec::new();
    let mut missing: Vec<String> = Vec::new();

    for (name, emf_bytes) in &corpus.sources {
        let Some(golden_svg) = corpus.goldens.get(name) else {
            continue;
        };
        let Some(ruby_bytes) = corpus.reverse_goldens.get(name) else {
            missing.push(name.clone());
            continue;
        };
        match round_trip(emf_bytes) {
            Ok((svg, bytes)) => {
                // The SVG comparison applies the documented quirk
                // normalization (the whitespace the XML grammar discards);
                // the EMF comparison is raw bytes.
                let svg_matches = normalize_quirks(&svg) == normalize_quirks(golden_svg);
                if svg_matches && &bytes == ruby_bytes {
                    matched.push(name.clone());
                } else {
                    let detail = if !svg_matches {
                        format!(
                            "forward SVG diverges: {}",
                            first_diff(
                                normalize_quirks(golden_svg).as_bytes(),
                                normalize_quirks(&svg).as_bytes()
                            )
                        )
                    } else {
                        first_diff(ruby_bytes, &bytes)
                    };
                    mismatches.push((name.clone(), detail));
                }
            }
            Err(error) => errors.push((name.clone(), error)),
        }
    }

    eprintln!("=== EMF → VIM → SVG → VIM → EMF round-trip gate ===");
    eprintln!(
        "corpus: {} sources, {} goldens, {} reverse goldens",
        corpus.sources.len(),
        corpus.goldens.len(),
        corpus.reverse_goldens.len()
    );
    eprintln!(
        "match (both forward SVG and final EMF bytes): {}",
        matched.len()
    );
    eprintln!("mismatch: {}", mismatches.len());
    eprintln!("error: {}", errors.len());
    eprintln!("missing reverse golden: {}", missing.len());
    for (name, error) in errors.iter().take(8) {
        eprintln!("  error {name}: {error}");
    }
    for (name, diff) in mismatches.iter().take(8) {
        eprintln!("  mismatch {name}: {diff}");
    }
    assert!(
        mismatches.is_empty() && errors.is_empty(),
        "round-trip gate: match={} mismatch={} error={}",
        matched.len(),
        mismatches.len(),
        errors.len()
    );
}

#[test]
fn direct_translation_gate() {
    let Some(corpus) = load_corpus() else {
        eprintln!("parity corpus not configured; skipping");
        return;
    };

    let mut matched: Vec<String> = Vec::new();
    let mut mismatches: Vec<(String, String)> = Vec::new();
    let mut errors: Vec<(String, String)> = Vec::new();

    for (name, golden_svg) in &corpus.goldens {
        let Some(ruby_bytes) = corpus.reverse_goldens.get(name) else {
            continue;
        };
        match direct(golden_svg) {
            Ok(bytes) => {
                if &bytes == ruby_bytes {
                    matched.push(name.clone());
                } else {
                    mismatches.push((name.clone(), first_diff(ruby_bytes, &bytes)));
                }
            }
            Err(error) => errors.push((name.clone(), error)),
        }
    }

    eprintln!("=== SVG → VIM → EMF direct translation gate ===");
    eprintln!("match (raw bytes): {}", matched.len());
    eprintln!("mismatch: {}", mismatches.len());
    eprintln!("error: {}", errors.len());
    for (name, error) in errors.iter().take(8) {
        eprintln!("  error {name}: {error}");
    }
    for (name, diff) in mismatches.iter().take(8) {
        eprintln!("  mismatch {name}: {diff}");
    }
    assert!(
        mismatches.is_empty() && errors.is_empty(),
        "direct gate: match={} mismatch={} error={}",
        matched.len(),
        mismatches.len(),
        errors.len()
    );
}

/// Dumps every direct-translation output for offline signature analysis
/// (run with EMF_DUMP_DIR=<path>; writes <name>.emf per fixture).
#[test]
fn dump_direct_outputs() {
    let Ok(dir) = std::env::var("EMF_DUMP_DIR") else {
        return;
    };
    let Some(corpus) = load_corpus() else {
        eprintln!("parity corpus not configured; skipping");
        return;
    };
    std::fs::create_dir_all(&dir).expect("create dump dir");
    let mut written = 0usize;
    let mut failed = 0usize;
    for (name, golden_svg) in &corpus.goldens {
        match direct(golden_svg) {
            Ok(bytes) => {
                std::fs::write(std::path::Path::new(&dir).join(format!("{name}.emf")), &bytes)
                    .expect("write dump");
                written += 1;
            }
            Err(error) => {
                eprintln!("dump {name}: {error}");
                failed += 1;
            }
        }
    }
    eprintln!("dumped {written} outputs ({failed} failures) to {dir}");
}

/// Per-file gate for a single name (debugging helper; run with
/// PARITY_ONE=<name> and PARITY_OUT=<path> for byte dumps).
#[test]
fn parity_single_file() {
    let Ok(name) = std::env::var("PARITY_ONE") else {
        return;
    };
    let Some(corpus) = load_corpus() else {
        return;
    };
    let Some(emf_bytes) = corpus.sources.get(&name) else {
        panic!("no EMF source for {name}");
    };
    let golden_svg = corpus.goldens.get(&name).expect("golden SVG");
    let ruby_bytes = corpus.reverse_goldens.get(&name).expect("reverse golden");
    match round_trip(emf_bytes) {
        Ok((svg, bytes)) => {
            if let Ok(out_path) = std::env::var("PARITY_OUT") {
                std::fs::write(&out_path, &bytes).expect("write PARITY_OUT");
                eprintln!("round-trip bytes written to {out_path}");
            }
            if normalize_quirks(&svg) != normalize_quirks(golden_svg) {
                panic!(
                    "{name}: forward SVG diverges: {}",
                    first_diff(
                        normalize_quirks(golden_svg).as_bytes(),
                        normalize_quirks(&svg).as_bytes()
                    )
                );
            }
            if &bytes == ruby_bytes {
                println!("{name}: raw byte match");
            } else {
                panic!("{name}: {}", first_diff(ruby_bytes, &bytes));
            }
        }
        Err(error) => panic!("{name}: {error}"),
    }
}
